#!/usr/bin/env node
/**
 * Writes public/.htaccess for static cPanel hosting.
 * Reads projectsEnabled from src/content/projects.ts so disabled
 * project routes get real 301s instead of soft-200 meta-refresh pages.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const projectsSource = readFileSync(
  join(root, "src/content/projects.ts"),
  "utf8",
);
const projectsEnabled = /export const projectsEnabled\s*=\s*true/.test(
  projectsSource,
);

const projectsBlock = projectsEnabled
  ? `# Projects enabled - no stub redirects.`
  : `# Projects disabled: real 301s instead of soft-200 stubs
RewriteRule ^(en|fa)/projects/?$ /$1/ [R=301,L]
RewriteRule ^(en|fa)/projects/.+/?$ /$1/ [R=301,L]`;

const htaccess = `# Apache helpers for static Next.js export on cPanel
# Generated by scripts/generate-htaccess.mjs - do not edit by hand.
DirectoryIndex index.html

RewriteEngine On

# Canonical host: www -> apex
RewriteCond %{HTTP_HOST} ^www\\.(.+)$ [NC]
RewriteRule ^ https://%1%{REQUEST_URI} [L,R=301]

# Force HTTPS first (avoids http -> locale -> https chains)
RewriteCond %{HTTPS} !=on
RewriteCond %{HTTP:X-Forwarded-Proto} !https
RewriteRule ^ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]

# Bare domain -> default locale (permanent)
RewriteRule ^$ /en/ [R=301,L]

${projectsBlock}
`;

writeFileSync(join(root, "public/.htaccess"), htaccess, "utf8");
console.log(
  `Wrote public/.htaccess (projectsEnabled=${projectsEnabled})`,
);
